'use strict';
// Builds command replies (spec §29/§33 + AI control center) from stored state. Commands never
// spend AI requests, except the user-requested 🔮 BIGGEST SCENARIOS explanation (priority 4, cached).
const { loadConfig, describeConfig } = require('../../lib/config');
const T = require('../../lib/telegram');
const TA = require('../../lib/telegram-ai');
const M = require('../../lib/telegram-menu');
const TD = require('../../lib/telegram-direction');
const B = require('../../lib/biggest');
const { marketSnapshot, agedSourceQuality } = require('../../lib/market');
const { currentState } = require('../../lib/preevent');
const { EVENT_TYPES } = require('../../lib/calendar');

const cfg = loadConfig($env);
const cfgView = describeConfig(cfg);
const tz = cfg.timezone;
const up = $('Route Updates').first().json;
const d = $input.first().json;
const allowed = new Set(cfg.telegram.chatIds.map(String));
const setupMode = allowed.size === 0;
const messages = [];
const inbound = [];
const aiRequests = [];

const deskFinal = d.desk || null;
const desk = deskFinal && deskFinal.desk ? deskFinal.desk : null;
const ser = (a) => (a || []).map((p) => ({ t: p.t, v: Number(p.v) }));
const snap = marketSnapshot({
  GOLD: ser(d.gold), USD_PROXY: ser(d.usd), US2Y: ser(d.us2y), US10Y: ser(d.us10y), US10Y_REAL: ser(d.us10y_real), WTI: ser(d.wti), GOLD_COT_NONCOMM_NET: ser(d.cot),
}, new Date().toISOString());
const state = currentState(snap);
const events = d.events || [];
const byCat = (cat) => events.filter((e) => e.category === cat).sort((a, b) => b.importance_score - a.importance_score);
const catSummary = {};
for (const c of ['GEOPOLITICS', 'POLITICS', 'MACRO']) {
  const top = byCat(c)[0];
  if (top) catSummary[c] = `${top.title} (${top.importance_class}, ${top.net_pressure})`;
}
const label = (t) => (EVENT_TYPES[t] || {}).label || t;
const upcoming = (d.upcoming || []).map((u) => ({ ...u, label: label(u.event_type) }));
const forecasts = (d.forecasts || []).map((f) => ({ ...f, label: label(f.event_type) }));
// Next MAJOR event: prefer the next HIGH-impact release, attach its stored forecast if any.
const major = upcoming.find((u) => u.impact === 'HIGH') || upcoming[0] || null;
const next = major ? { ...major, forecast: forecasts.find((f) => Number(f.macro_release_id) === Number(major.id)) || null } : null;
let usageView = null;
const deskDq = () => (desk && desk.source_quality ? agedSourceQuality(desk.source_quality, desk.as_of, new Date().toISOString(), cfg.schedule.marketIntervalMin) : null);
const usage = () => { usageView = usageView || TA.buildUsageView(d.ai_usage, cfg, cfgView, new Date().toISOString()); return usageView; };

/** @returns {{text:string, reply_markup?:object, ai?:object, biggest?:Array}} */
function reply(cmd, args) {
  const sub = String(args[0] || '').toLowerCase();
  switch (cmd) {
    case '/':
    case '/menu':
    case '/start': return { text: M.formatMenu(tz), reply_markup: M.MAIN_MENU_KEYBOARD };
    case '/now':
      if (!desk) return { text: '<b>XAUUSD — NOW</b>\nDesk state not computed yet (market run pending). Try again after the next market tick.' };
      return { text: TD.formatGoldNow(desk, state, catSummary, next, tz, { layers: desk.layers || null, dataQuality: deskDq(), cells: d.calibration || [], cfg: cfg.calibration }), reply_markup: M.BACK_TO_MENU };
    case '/daily': {
      const rep = d.daily;
      if (!rep || !rep.final || !rep.final.text) return { text: 'No daily report generated yet today.' };
      return { text: rep.final.text };
    }
    case '/geopolitics': return { text: T.formatEventList('🌍 TOP GEOPOLITICS (48h)', byCat('GEOPOLITICS'), tz) };
    case '/politics': return { text: T.formatEventList('🏛 TOP POLITICS (48h)', byCat('POLITICS'), tz) };
    case '/macro': return { text: T.formatEventList('📈 TOP MACRO (48h)', byCat('MACRO'), tz) };
    case '/gold': return { text: T.formatEventList('🟡 GOLD FUNDAMENTALS & MARKET (48h)', [...byCat('GOLD'), ...byCat('MARKET')], tz) };
    case '/events': {
      if (!upcoming.length) return { text: '<b>UPCOMING EVENTS</b>\nNo scheduled high/medium-impact events in the next 7 days.' };
      return { text: ['<b>🗓 UPCOMING EVENTS (7d)</b>', ...upcoming.slice(0, 10).map((u) => { const f = forecasts.find((x) => Number(x.macro_release_id) === Number(u.id)); return `• ${T.esc(T.localTime(u.scheduled_at, tz))} — ${T.esc(u.label)} (${T.esc(u.impact)})${u.consensus ? ` · cons ${T.esc(u.consensus)}` : ''}${f ? ` · forecast ${T.esc(f.forecast_state)} (score ${T.esc(f.pre_event_score)}, conf ${T.esc(f.confidence)})` : ''}`; })].join('\n') };
    }
    case '/scenarios': {
      const f = d.scenarios;
      if (!f || !f.scenarios || !f.scenarios.length) return { text: 'No pre-event scenarios stored yet. They are generated by the daily pre-event run.' };
      const sc = Object.fromEntries(f.scenarios.map((s) => [s.kind, s]));
      const fmt = (s) => (s ? `Trigger: ${T.esc(s.trigger_text)}\nMechanism: ${T.esc(s.mechanism)}\nGold: ${T.esc(s.expected_gold_response)}\nInvalidation: ${T.esc(s.invalidation)}` : 'n/a');
      return { text: [`<b>🧭 SCENARIOS — ${T.esc(f.label || f.event_type)}</b> (${T.esc(T.localTime(f.scheduled_at, tz))})`, `Pre-event bias: ${T.esc(f.pre_event_bias)} · confidence ${T.esc(f.confidence)}`, '', '🟢 <b>BULLISH</b>', fmt(sc.BULLISH), '', '🔴 <b>BEARISH</b>', fmt(sc.BEARISH), '', '⚪ <b>BASE / MIXED</b>', fmt(sc.BASE)].join('\n') };
    }
    case '/biggest': {
      const ranked = B.withProbabilities(B.rankScenarios((d.biggest || []).map((f) => ({ ...f, label: label(f.event_type) }))), d.calibration || []);
      if (!ranked.length) return { text: B.formatBiggest([], null, tz) };
      const facts = B.biggestFacts(ranked, desk);
      const ref = `biggest:${ranked.map((s) => `${s.release_key}:${s.kind}`).join('|')}`;
      const ai = { ref, purpose: 'BIGGEST', use_ai: cfg.secrets.openrouterConfigured, is_test: Boolean(up.simulated), facts,
        deterministic: B.deterministicBiggest(facts), timeout_ms: cfg.ai.botTimeoutMs, max_attempts: 2 };
      return { text: B.formatBiggest(ranked, { label: cfg.secrets.openrouterConfigured ? 'deterministic — AI explanation pending' : 'deterministic (OPENROUTER_API_KEY not configured)' }, tz), ai, biggest: ranked };
    }
    case '/news': return { text: M.formatNews(events, tz), reply_markup: M.BACK_TO_MENU };
    case '/market': {
      const dq = desk && desk.source_quality ? agedSourceQuality(desk.source_quality, desk.as_of, new Date().toISOString(), cfg.schedule.marketIntervalMin) : null;
      return { text: M.formatMarketState(state, desk, dq, tz), reply_markup: M.BACK_TO_MENU };
    }
    case '/bias': return { text: M.formatBias(forecasts, tz), reply_markup: M.BACK_TO_MENU };
    case '/history': return { text: M.formatHistory(d.history || [], args[0]), reply_markup: M.BACK_TO_MENU };
    case '/alerts': return { text: M.formatAlerts(d.recent_alerts || [], d.alert_grade || [], tz), reply_markup: M.BACK_TO_MENU };
    case '/review': return { text: M.formatReview(d.reviews || [], d.recent_reactions || [], d.performance || {}, tz), reply_markup: M.BACK_TO_MENU };
    case '/analysis': {
      const dq = deskDq();
      return { text: [...TD.directionSummary(desk, d.calibration || [], dq ? dq.level : null, cfg.calibration), '', M.formatAnalysis(d.analyses || [], tz)].join('\n'), reply_markup: M.BACK_TO_MENU };
    }
    case '/status': return { text: T.formatStatus({ ...(d.health || { checked_at: new Date().toISOString(), overall: 'UNKNOWN', components: [], ai_used_today: 0 }), extra: d.status_extra || {} }, cfgView, tz) };
    case '/event': {
      const id = Number(args[0]);
      const ev = (d.requested_events || []).find((e) => Number(e.id) === id) || (!args[0] ? (d.requested_events || [])[0] : null);
      return { text: ev ? T.formatEventDetail(ev, tz) : 'Usage: /event &lt;id&gt; (ids are shown in /geopolitics, /macro, ...).' };
    }
    case '/usage':
    case '/ai_usage': return { text: TA.formatUsageCenter(usage(), tz), reply_markup: TA.BACK_TO_AI };
    case '/ai': {
      const u = usage();
      if (!sub) return { text: TA.formatAiMenu(u, tz), reply_markup: TA.AI_MENU_KEYBOARD };
      const views = {
        usage: () => TA.formatUsageCenter(u, tz), health: () => TA.formatAiHealth(u, tz), model: () => TA.formatAiModel(u, tz),
        fallback: () => TA.formatAiFallback(u, tz), config: () => TA.formatAiConfig(u), configuration: () => TA.formatAiConfig(u),
        failures: () => TA.formatAiFailures(u, tz), performance: () => TA.formatAiPerformance(u.performance),
      };
      if (views[sub]) return { text: views[sub](), reply_markup: TA.BACK_TO_AI };
      return { text: `Unknown /ai view. Use: ${Object.keys(views).filter((k) => k !== 'configuration').map((k) => `/ai ${k}`).join(' · ')}`, reply_markup: TA.AI_MENU_KEYBOARD };
    }
    default: return { text: `Unknown command. Available: ${T.COMMANDS.join(' ')}` };
  }
}

for (const u of up.updates || []) {
  const msg = u.message;
  if (!msg || !msg.chat) continue;
  const chatId = String(msg.chat.id);
  const text = String(msg.text || '').slice(0, 200);
  const parsed = T.parseCommand(text);
  const authorised = allowed.has(chatId) || (up.simulated && chatId === 'SIMULATED_CHAT');
  inbound.push({ chat_id: chatId, body: text, status: authorised ? 'RECEIVED' : 'IGNORED', message_type: u.via_button ? 'BUTTON' : 'COMMAND', is_test: Boolean(up.simulated) });
  if (!parsed) continue;
  if (!authorised) {
    if (setupMode && parsed.command === '/start') {
      messages.push({ chat_id: chatId, text: T.formatStart(chatId, false), message_type: 'COMMAND_REPLY', related_ref: 'setup', is_test: Boolean(up.simulated) });
    }
    continue;
  }
  const r = reply(parsed.command, parsed.args);
  const shown = [parsed.command, ...parsed.args.slice(0, 1)].join(' ');
  const m = {
    chat_id: chatId === 'SIMULATED_CHAT' ? null : chatId,
    text: `${up.simulated ? '🧪 <i>simulated command</i> ' : ''}<code>${T.esc(shown)}</code>\n${r.text}`,
    message_type: 'COMMAND_REPLY', related_ref: shown, is_test: Boolean(up.simulated),
    ...(r.reply_markup ? { reply_markup: r.reply_markup } : {}),
  };
  if (r.ai && r.ai.use_ai) {
    aiRequests.push(r.ai);
    m.ai_ref = r.ai.ref;
    m.biggest = r.biggest;
    m.prefix = `${up.simulated ? '🧪 <i>simulated command</i> ' : ''}<code>${T.esc(shown)}</code>\n`;
  }
  messages.push(m);
}
// De-duplicate identical AI requests in one batch (e.g. two /biggest presses).
const uniqueAi = aiRequests.filter((r, i, a) => a.findIndex((x) => x.ref === r.ref) === i);
return [{ json: { payload: { messages }, ai_payload: { workflow: 'bot', requests: uniqueAi }, has_ai: uniqueAi.length > 0, save: { offset: up.simulated ? null : up.new_offset, inbound } } }];
